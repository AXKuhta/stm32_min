static void gc2145_i2c_write(uint8_t buf[], size_t sz) {
	if (HAL_OK != HAL_I2C_Master_Transmit(&sccb, 0x78, buf, sz, 1000)) while (1) {};
}

// Ensure called -after- dcmi init
static void dcmi_dma_init() {
	__HAL_RCC_DMA1_CLK_ENABLE();

	HAL_NVIC_SetPriority(DMA1_Stream1_IRQn, 0, 0);
	HAL_NVIC_EnableIRQ(DMA1_Stream1_IRQn);

	hdma_dcmi = (DMA_HandleTypeDef) {
		.Instance = DMA1_Stream1,
		.Init = {
			.Request             = DMA_REQUEST_DCMI,
			.Direction           = DMA_PERIPH_TO_MEMORY,
			.PeriphInc           = DMA_PINC_DISABLE,
			.MemInc              = DMA_MINC_ENABLE,
			.PeriphDataAlignment = DMA_PDATAALIGN_WORD,
			.MemDataAlignment    = DMA_MDATAALIGN_WORD,
			.Mode                = DMA_NORMAL,
			.Priority            = DMA_PRIORITY_MEDIUM
		}
	};

	if (HAL_DMA_Init(&hdma_dcmi) != HAL_OK) {
		while (1) {}
	}

	__HAL_LINKDMA(&hdcmi, DMA_Handle, hdma_dcmi);
}

// 0x09 Sensor readout window
// 0x91 Crop window
static void set_window(uint8_t reg, uint16_t x, uint16_t y, uint16_t w, uint16_t h) {
	gc2145_i2c_write((uint8_t[]){0xFE,  0x00     }, 2);
	gc2145_i2c_write((uint8_t[]){reg++, y >> 8   }, 2);
	gc2145_i2c_write((uint8_t[]){reg++, y  & 0xff}, 2);
	gc2145_i2c_write((uint8_t[]){reg++, x >> 8   }, 2);
	gc2145_i2c_write((uint8_t[]){reg++, x  & 0xff}, 2);
	gc2145_i2c_write((uint8_t[]){reg++, h >> 8   }, 2);
	gc2145_i2c_write((uint8_t[]){reg++, h  & 0xff}, 2);
	gc2145_i2c_write((uint8_t[]){reg++, w >> 8   }, 2);
	gc2145_i2c_write((uint8_t[]){reg++, w  & 0xff}, 2);
}

#define BLANK_LINES             16
#define DUMMY_LINES             16

#define BLANK_COLUMNS           0
#define DUMMY_COLUMNS           8

#define SENSOR_WIDTH            1616
#define SENSOR_HEIGHT           1248

#define ACTIVE_SENSOR_WIDTH     (SENSOR_WIDTH - BLANK_COLUMNS - (2 * DUMMY_COLUMNS))
#define ACTIVE_SENSOR_HEIGHT    (SENSOR_HEIGHT - BLANK_LINES - (2 * DUMMY_LINES))

#define DUMMY_WIDTH_BUFFER      16
#define DUMMY_HEIGHT_BUFFER     8

static int16_t readout_x = 0;
static int16_t readout_y = 0;

static uint16_t readout_w = ACTIVE_SENSOR_WIDTH;
static uint16_t readout_h = ACTIVE_SENSOR_HEIGHT;

static bool fov_wide = false;

#define MAX(a, b) (a > b ? a : b)
#define MIN(a, b) (a < b ? a : b)
#define CLAMP(x, min, max)    MAX(MIN((x), (max)), (min))

static void set_framesize(uint16_t w, uint16_t h) {
	// Invalid resolution.
	if ((w > ACTIVE_SENSOR_WIDTH) || (h > ACTIVE_SENSOR_HEIGHT)) while(1) {};

	// Step 0: Clamp readout settings.
	readout_w = MAX(readout_w, w);
	readout_h = MAX(readout_h, h);

	int readout_x_max = (ACTIVE_SENSOR_WIDTH - readout_w) / 2;
	int readout_y_max = (ACTIVE_SENSOR_HEIGHT - readout_h) / 2;
	readout_x = CLAMP(readout_x, -readout_x_max, readout_x_max);
	readout_y = CLAMP(readout_y, -readout_y_max, readout_y_max);

	// Step 1: Determine sub-readout window.

	uint16_t ratio = MIN(readout_w / ((float) w), readout_h / ((float) h));

	// Limit the maximum amount of scaling allowed to keep the frame rate up.
	ratio = MIN(ratio, (fov_wide ? 5 : 3));

	if (!(ratio % 2)) {
		// camera outputs messed up bayer images at even ratios for some reason...
		ratio -= 1;
	}

	uint16_t sub_readout_w = w * ratio;
	uint16_t sub_readout_h = h * ratio;

	// Step 2: Determine horizontal and vertical start and end points.

	uint16_t sensor_w = sub_readout_w + DUMMY_WIDTH_BUFFER; // camera hardware needs dummy pixels to sync
	uint16_t sensor_h = sub_readout_h + DUMMY_HEIGHT_BUFFER; // camera hardware needs dummy lines to sync

	uint16_t sensor_x = CLAMP((((ACTIVE_SENSOR_WIDTH - sensor_w) / 4) - (readout_x / 2)) * 2,
	                         -(DUMMY_WIDTH_BUFFER / 2), ACTIVE_SENSOR_WIDTH - sensor_w) + DUMMY_COLUMNS; // must be multiple of 2

	uint16_t sensor_y = CLAMP((((ACTIVE_SENSOR_HEIGHT - sensor_h) / 4) - (readout_y / 2)) * 2,
	                         -(DUMMY_HEIGHT_BUFFER / 2), ACTIVE_SENSOR_HEIGHT - sensor_h) + DUMMY_LINES; // must be multiple of 2

	// Step 3: Write regs.

	// Set Readout window first.
	set_window(0x09, sensor_x, sensor_y, sensor_w, sensor_h);

	// Set cropping window next.
	set_window(0x91, 0, 0, w, h);

	// Enable crop
	gc2145_i2c_write((uint8_t[]){0x90, 0x01}, 2);

	// Set Sub-sampling ratio and mode
	gc2145_i2c_write((uint8_t[]){0x99, ((ratio << 4) | (ratio))}, 2);
	gc2145_i2c_write((uint8_t[]){0x9A, 0x0E}, 2);
}

void init_gc2145() {
	__HAL_RCC_GPIOA_CLK_ENABLE();
	__HAL_RCC_GPIOB_CLK_ENABLE();
	__HAL_RCC_GPIOC_CLK_ENABLE();
	__HAL_RCC_GPIOD_CLK_ENABLE();
	__HAL_RCC_GPIOE_CLK_ENABLE();

	HAL_GPIO_Init(GPIOE, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_7, .Mode = GPIO_MODE_OUTPUT_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST });
	HAL_GPIO_Init(GPIOE, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_8, .Mode = GPIO_MODE_OUTPUT_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST });
	HAL_GPIO_Init(GPIOA, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_5, .Mode = GPIO_MODE_OUTPUT_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST });

	HAL_GPIO_Init(GPIOC, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_6, .Mode = GPIO_MODE_AF_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST, .Alternate = GPIO_AF13_DCMI });
	HAL_GPIO_Init(GPIOC, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_7, .Mode = GPIO_MODE_AF_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST, .Alternate = GPIO_AF13_DCMI });
	HAL_GPIO_Init(GPIOC, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_8, .Mode = GPIO_MODE_AF_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST, .Alternate = GPIO_AF13_DCMI });
	HAL_GPIO_Init(GPIOC, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_9, .Mode = GPIO_MODE_AF_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST, .Alternate = GPIO_AF13_DCMI });

	HAL_GPIO_Init(GPIOE, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_4, .Mode = GPIO_MODE_AF_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST, .Alternate = GPIO_AF13_DCMI });
	HAL_GPIO_Init(GPIOD, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_3, .Mode = GPIO_MODE_AF_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST, .Alternate = GPIO_AF13_DCMI });
	HAL_GPIO_Init(GPIOE, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_5, .Mode = GPIO_MODE_AF_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST, .Alternate = GPIO_AF13_DCMI });
	HAL_GPIO_Init(GPIOE, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_6, .Mode = GPIO_MODE_AF_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST, .Alternate = GPIO_AF13_DCMI });

	HAL_GPIO_Init(GPIOA, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_4, .Mode = GPIO_MODE_AF_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST, .Alternate = GPIO_AF13_DCMI });
	HAL_GPIO_Init(GPIOB, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_7, .Mode = GPIO_MODE_AF_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST, .Alternate = GPIO_AF13_DCMI });
	HAL_GPIO_Init(GPIOA, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_6, .Mode = GPIO_MODE_AF_PP, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST, .Alternate = GPIO_AF13_DCMI });

	HAL_GPIO_Init(GPIOD, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_12, .Mode = GPIO_MODE_AF_OD, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST, .Alternate = GPIO_AF4_I2C4 });
	HAL_GPIO_Init(GPIOD, &(GPIO_InitTypeDef){ .Pin = GPIO_PIN_13, .Mode = GPIO_MODE_AF_OD, .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FAST, .Alternate = GPIO_AF4_I2C4 });

	HAL_GPIO_WritePin(GPIOE, GPIO_PIN_7, 0);
	HAL_GPIO_WritePin(GPIOE, GPIO_PIN_8, 0);
	HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, 1);

	HAL_Delay(10);

	HAL_GPIO_WritePin(GPIOE, GPIO_PIN_7, 1);
	HAL_GPIO_WritePin(GPIOE, GPIO_PIN_8, 0);
	HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, 0);

	HAL_Delay(10);

	__HAL_RCC_DCMI_CLK_ENABLE();
	__HAL_RCC_I2C4_CLK_ENABLE();

	sccb = (I2C_HandleTypeDef) {
		.Instance = I2C4,
		.Init = {
			.AddressingMode  = I2C_ADDRESSINGMODE_7BIT,
			.Timing          = 0xB0C33131, // ~100 kHz assuming 120 MHZ bus clock
			.DualAddressMode = I2C_DUALADDRESS_DISABLED,
			.GeneralCallMode = I2C_GENERALCALL_ENABLED,
			.NoStretchMode   = I2C_NOSTRETCH_DISABLED,
			.OwnAddress1     = 0xFE,
			.OwnAddress2     = 0xFE
		}
	};

	if (HAL_OK != HAL_I2C_Init(&sccb)) while (1) {};

	// Enable the module
	for (int i = 0; sccb_on_command[i][0] != 0; i++) {
		gc2145_i2c_write(sccb_on_command[i], 2);
	}

	hdcmi = (DCMI_HandleTypeDef) {
		.Instance = DCMI,
		.Init = {
			.VSPolarity  = DCMI_VSPOLARITY_LOW,
			.HSPolarity  = DCMI_HSPOLARITY_LOW,
			.PCKPolarity = DCMI_PCKPOLARITY_RISING,
			.SynchroMode = DCMI_SYNCHRO_HARDWARE,
			.CaptureRate = DCMI_CR_ALL_FRAME,
			.ExtendedDataMode = DCMI_EXTEND_DATA_8B,
			.JPEGMode = 0
		}
	};

	HAL_NVIC_SetPriority(DCMI_IRQn, 8, 0);
	HAL_NVIC_EnableIRQ(DCMI_IRQn);

	if (HAL_OK != HAL_DCMI_Init(&hdcmi)) while (1) {};

	set_framesize(1600, 64);

	dcmi_dma_init();

}

_Alignas(4) uint16_t fb[320*320] = {0};

uint32_t errors = 0;

void gc2145_capture() {
	HAL_DCMI_Start_DMA(&hdcmi, DCMI_MODE_SNAPSHOT, (uint32_t)(void*)fb, sizeof(fb)/4);

	uint32_t timeout = HAL_GetTick() + 1000;

	while (HAL_DCMI_GetState(&hdcmi) == HAL_DCMI_STATE_BUSY) {
		if (HAL_GetTick() > timeout) {
			HAL_DCMI_Stop(&hdcmi);
			errors++;
			return;
		}
	}
}
